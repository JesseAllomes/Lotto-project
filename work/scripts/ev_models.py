KENO_NOW = {"classic10": 1_165_342.85, "mm10": 5_128_957.64, "classic9": 234_589.56,
            "classic8": 32_080.50, "classic7": 5_320.92}


def keno_ev(table, spots, jackpot, price):
    fixed = 0.0
    pj = 0.0
    for k, prize in table[spots].items():
        p = hyper(k, spots)
        if prize == "J":
            pj = p
        else:
            fixed += p * prize
    return fixed, pj, (fixed + pj * jackpot) / price


