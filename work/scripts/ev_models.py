lines = []


def say(s=""):
    print(s)
    lines.append(s)


def share_factor(lam):
    """E[1/(1+N)] * (1+lam) where N~Poisson(lam): expected fraction of a pari-mutuel
    pool a winner keeps = (1-exp(-lam))/lam (lam = expected number of OTHER winners)."""
    return 1.0 if lam == 0 else (1 - exp(-lam)) / lam


# ----------------------------------------------------------------------------- Keno
def hyper(k, spots, drawn=20, total=80):
    return comb(spots, k) * comb(total - spots, drawn - k) / comb(total, drawn)


