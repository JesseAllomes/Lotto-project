"""Expected-value models for Australian lottery games.

Inputs: official rule parameters (hard-coded below with the source they came from) and
The Lott API draw files in ../data (latest10_*.json) plus ../data/big_draws.json.

Run:  python3 -I ev_models.py            (prints the summary; writes ../ev_results.md)

All probabilities are exact combinatorics. "Retail" prices are Lotterywest's published
prices (include retailer commission); "subscription" = retail less commission. The
commission ratio is only known exactly for Powerball ($1.40 subscription vs $1.575 retail,
Lotterywest Powerball update + price PDF), so the same 11.1% is assumed for other games.
"""
