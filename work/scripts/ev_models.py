NDIV1 = {"Powerball": 134_490_400, "OzLotto": 62_891_499, "TattsLotto": 8_145_060}
PRICE = {"Powerball": (1.40, 1.575), "OzLotto": (1.30, 1.45), "TattsLotto": (0.85, 0.95)}  # (subscription est., retail)


def infer(game, divisions, sub_price):
    """divisions: list of (div, winners, dividend). Prize fund inferred as the median of
    pool/allocation over non-jackpot divisions (robust to one boosted division)."""
    ests = []
    paid = 0.0
    for div, w, dv in divisions:
        paid += w * dv
        if div != 1 and w > 0:
            ests.append(w * dv / ALLOC[game][div])
    ests.sort()
    pf = ests[len(ests) // 2]
    games = pf / 0.55 / sub_price
    return pf, games, paid


def ev_jackpot_game(game, J, games, sub_price, retail):
    N = NDIV1[game]
    lam = games / N
    div1 = J * share_factor(lam) / N
    lower = 0.55 * (1 - ALLOC[game][1]) * sub_price
    return div1, lower, (div1 + lower) / retail


