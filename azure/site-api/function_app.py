"""Static Web App managed API (Azure Functions, Python): the one route /api/action.

All the logic is in lotto_actions.py (stdlib only, tested offline); this file only adapts it to Azure Functions.
The route is public (no login anywhere on the site; staticwebapp.config.json, generated by workers/site.py, 404s every
login provider), so lotto_actions.handle enforces validation, size limits and a per-client-IP rate cap (429).  The queue
SAS is the app setting ACTIONS_QUEUE_SAS.
"""
import json
import os

import azure.functions as func

import lotto_actions

app = func.FunctionApp(http_auth_level=func.AuthLevel.ANONYMOUS)


@app.route(route="action", methods=["POST"])
def action(req: func.HttpRequest) -> func.HttpResponse:
    status, payload = lotto_actions.handle(req.method, dict(req.headers), req.get_body(), os.environ)
    return func.HttpResponse(json.dumps(payload), status_code=status, mimetype="application/json",
                             headers={"Cache-Control": "no-store"})
